//! Build contexts: the derived system image (bootc) and the toolbox image.
//!
//! Both are plain Containerfiles written next to the plan so the user can read,
//! tweak and rebuild them; Plexy never hides what it layers onto the system.

use crate::manifest::Manifest;
use crate::os::Family;
use crate::plan::{ConfigAction, Dest, Plan};
use crate::util::{self, info, root_join, shq, write_file};
use anyhow::{Context, Result};
use std::fs;
use std::path::{Path, PathBuf};

/// Install command for a build. `tolerant` (toolboxes) skips individual
/// packages that conflict instead of failing the whole build; `replacing`
/// lets packages that replace base packages (libwacom-surface) remove them.
fn install_cmd(family: Family, pkgs: &[String], tolerant: bool, replacing: bool) -> String {
    let list = pkgs
        .iter()
        .map(|p| shq(p))
        .collect::<Vec<_>>()
        .join(" \\\n        ");
    match family {
        Family::Debian => format!(
            "RUN (lpkg --unlock >/dev/null 2>&1 || true) && apt-get update && \\\n    DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends \\\n        {list} && \\\n    rm -rf /var/lib/apt/lists/* && \\\n    (lpkg --lock >/dev/null 2>&1 || true)"
        ),
        // Tolerant builds also ride out an unreachable third-party mirror.
        _ => format!(
            "RUN dnf -y install --setopt=install_weak_deps=False --setopt=retries=10 --skip-unavailable{}{} \\\n        {list} && \\\n    dnf clean all",
            if tolerant {
                " --skip-broken --setopt=skip_if_unavailable=True"
            } else {
                ""
            },
            if replacing { " --allowerasing" } else { "" }
        ),
    }
}

/// Copy repository definitions and their signing keys into `ctx/repos/...`
/// preserving absolute paths, and return the COPY instructions.
fn stage_repos(m: &Manifest, files: &[String], ctx: &Path) -> Result<Vec<String>> {
    let mut lines = vec![];
    let mut wanted: Vec<String> = vec![];
    for r in m.repos.iter().filter(|r| files.contains(&r.path)) {
        wanted.push(r.path.clone());
        // dnf variables appear in key paths (RPM-GPG-KEY-rpmfusion-free-fedora-$releasever)
        wanted.extend(
            r.keys
                .iter()
                .map(|k| expand_dnf_vars(k, &m.os.version_id, &m.os.arch)),
        );
    }
    // Repo files often reference keys indirectly; the rpm key directory is
    // small, so carry it whole for Fedora-family builds.
    let keydir = fs::read_dir("/etc/pki/rpm-gpg");
    if let (false, crate::os::Family::Fedora, Ok(rd)) = (wanted.is_empty(), m.os.family, keydir) {
        wanted.extend(rd.flatten().map(|e| e.path().display().to_string()));
    }
    wanted.sort();
    wanted.dedup();
    {
        for p in &wanted {
            let src = Path::new(p);
            if !src.exists() {
                continue;
            }
            let dst = root_join(&ctx.join("rootfs"), p);
            if let Some(d) = dst.parent() {
                fs::create_dir_all(d)?;
            }
            fs::copy(src, &dst).with_context(|| format!("copy {p}"))?;
        }
    }
    if ctx.join("rootfs").exists() {
        lines.push("COPY rootfs/ /".to_string());
    }
    Ok(lines)
}

pub fn expand_dnf_vars(s: &str, releasever: &str, arch: &str) -> String {
    s.replace(
        "$releasever_major",
        releasever.split('.').next().unwrap_or(releasever),
    )
    .replace("$releasever", releasever)
    .replace("$basearch", arch)
    .replace("$arch", arch)
}

/// Containerfile for the derived bootc image: target + repos + layered packages.
pub fn system_containerfile(m: &Manifest, plan: &Plan, ctx: &Path) -> Result<PathBuf> {
    let _ = fs::remove_dir_all(ctx);
    fs::create_dir_all(ctx)?;
    let mut cf = vec![
        "# Generated by plexy — derived image for this machine.".to_string(),
        format!(
            "# Source: {}  →  target: {}",
            plan.source, plan.target_image
        ),
        "# Edit freely, then: plexy build --plan <dir>".to_string(),
        format!("FROM {}", plan.target_image),
    ];
    let mut pkgs = plan.names_for(Dest::Image);
    if let Some(tb) = &plan.toolbox {
        // Toolbox mode needs a container runtime front-end on the host.
        if tb.engine == "distrobox" && !plan_target_has(plan, "distrobox") {
            pkgs.push("distrobox".into());
        }
    }
    cf.extend(stage_repos(m, &plan.repo_files, ctx)?);
    if !pkgs.is_empty() {
        let replacing = plan
            .by_dest(Dest::Image)
            .iter()
            .any(|p| !p.replaces.is_empty());
        cf.push(install_cmd(plan.target_family, &pkgs, false, replacing));
    }
    if plan.plexy_in_image {
        // /usr/local is read-only on this target: plexy's first-boot units
        // need the binary inside the image (it also survives rebuilds).
        fs::copy("/proc/self/exe", ctx.join("plexy"))?;
        cf.push("COPY plexy /usr/local/bin/plexy".into());
    }
    if plan.target_family == Family::Fedora {
        cf.push("RUN bootc container lint || true".into());
    }
    let p = ctx.join("Containerfile");
    write_file(&p, cf.join("\n") + "\n")?;
    Ok(p)
}

fn plan_target_has(plan: &Plan, pkg: &str) -> bool {
    plan.packages
        .iter()
        .any(|p| p.dest == Dest::Base && p.target_names.iter().any(|n| n == pkg))
}

/// Containerfile for the toolbox: the source distribution with every package
/// routed to the toolbox, its repositories, and the config those packages use.
pub fn toolbox_containerfile(m: &Manifest, plan: &Plan, ctx: &Path) -> Result<Option<PathBuf>> {
    let Some(tb) = &plan.toolbox else {
        return Ok(None);
    };
    let _ = fs::remove_dir_all(ctx);
    fs::create_dir_all(ctx)?;
    let mut cf = vec![
        "# Generated by plexy — your previous system's software, as a toolbox.".to_string(),
        format!("FROM {}", tb.base_image),
        "LABEL com.github.containers.toolbox=true".to_string(),
    ];
    cf.extend(stage_repos(m, &plan.toolbox_repo_files, ctx)?);
    // Configs that belong to containerised software.
    let etc_dir = ctx.join("etc-overlay");
    let mut any = false;
    for c in plan
        .configs
        .iter()
        .filter(|c| c.action == ConfigAction::Toolbox)
    {
        let src = Path::new(&c.path);
        if src.is_file() {
            let dst = root_join(&etc_dir, &c.path);
            fs::create_dir_all(dst.parent().unwrap())?;
            fs::copy(src, &dst)?;
            any = true;
        }
    }
    let mut pkgs = plan.names_for(Dest::Toolbox);
    pkgs.retain(|p| !crate::mapping::is_infrastructure(p));
    if !pkgs.is_empty() {
        cf.push(install_cmd(plan.source_family, &pkgs, true, false));
    }
    if any {
        cf.push("COPY etc-overlay/ /".into());
    }
    let p = ctx.join("Containerfile");
    write_file(&p, cf.join("\n") + "\n")?;
    Ok(Some(p))
}

pub fn podman_build(ctx: &Path, tag: &str) -> Result<()> {
    info(format!("building {tag} from {}", ctx.display()));
    let ctx = ctx.display().to_string();
    let args = [
        "build",
        "--pull=missing",
        "--network=host",
        "--security-opt",
        "label=disable",
        "-t",
        tag,
        &ctx,
    ];
    // Builds download hundreds of packages; one network blip (a DNS miss, a
    // mirror timeout) should not cost the whole run. Finished steps come from
    // the layer cache, so the retry only repeats the step that failed.
    if let Err(e) = util::run_visible("podman", &args) {
        util::warn(format!("{e:#}; retrying once in 30 s"));
        std::thread::sleep(std::time::Duration::from_secs(30));
        return util::run_visible("podman", &args);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dnf_var_expansion() {
        assert_eq!(
            expand_dnf_vars(
                "/etc/pki/rpm-gpg/RPM-GPG-KEY-rpmfusion-free-fedora-$releasever",
                "44",
                "x86_64"
            ),
            "/etc/pki/rpm-gpg/RPM-GPG-KEY-rpmfusion-free-fedora-44"
        );
        assert_eq!(expand_dnf_vars("k-$basearch", "44", "x86_64"), "k-x86_64");
    }

    #[test]
    fn install_commands_per_family() {
        let f = install_cmd(
            Family::Fedora,
            &["htop".into(), "nginx".into()],
            false,
            false,
        );
        assert!(
            f.contains("dnf -y install") && f.contains("htop") && f.contains("--skip-unavailable")
        );
        let d = install_cmd(Family::Debian, &["htop".into()], false, false);
        assert!(install_cmd(Family::Fedora, &["x".into()], true, false).contains("--skip-broken"));
        assert!(install_cmd(Family::Fedora, &["x".into()], false, true).contains("--allowerasing"));
        assert!(d.contains("apt-get install -y") && d.contains("rm -rf /var/lib/apt/lists"));
    }
}
