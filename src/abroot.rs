/// Per-root GRUB snippet on vos-init. The root is named by its device-mapper
/// path (as ABRoot itself writes it) so initramfs-tools activates the LV.
fn abroot_cfg(kver: &str, root_dev: &str, kargs: &str) -> String {
    format!(
        "insmod gzio\ninsmod part_gpt\ninsmod ext2\ninsmod lvm\n\
         linux   (lvm/vos--root-init)/vos-a/vmlinuz-{kver} root={root_dev} {kargs}\n\
         initrd  (lvm/vos--root-init)/vos-a/initrd.img-{kver}\n"
    )
}

/// Partitions plexy creates, by role.
#[derive(Debug, Clone)]
pub struct Layout {
    #[allow(dead_code)]
    pub disk: String,
    pub boot: String,
    pub pv: String,
    pub var: String,
}

fn part_dev(disk: &str, n: u32) -> String {
    if disk
        .chars()
        .last()
        .map(|c| c.is_ascii_digit())
        .unwrap_or(false)
    {
        format!("{disk}p{n}")
    } else {
        format!("{disk}{n}")
    }
}

/// sfdisk script lines for the three ABRoot partitions (key=value syntax;
/// sfdisk rejects positional fields mixed with name=). `var_mib` None = rest.
fn sfdisk_parts(var_mib: Option<u64>) -> String {
    let var = match var_mib {
        Some(m) => format!("size={m}MiB, "),
        None => String::new(),
    };
    format!(
        "size={BOOT_MIB}MiB, type=linux, name=vos-boot\nsize={ROOT_PV_MIB}MiB, type=lvm, name=vos-root\n{var}type=linux, name=vos-var\n"
    )
}

/// Free regions on a disk (start, size) in MiB, as reported by sfdisk.
fn free_regions(disk: &str) -> Vec<(u64, u64)> {
    let out = try_run("sfdisk", &["--list-free", "--bytes", disk]).unwrap_or_default();
    let mut v = vec![];
    for l in out.lines() {
        let f: Vec<&str> = l.split_whitespace().collect();
        // Start End Sectors Size
        if f.len() >= 4
            && let (Ok(start), Ok(bytes)) = (f[0].parse::<u64>(), f[3].parse::<u64>())
        {
            v.push((start * 512 / 1048576, bytes / 1048576));
        }
    }
    v
}

fn data_size_mib() -> u64 {
    let du = |p: &str| -> u64 {
        try_run("du", &["-sxm", p])
            .and_then(|o| o.split_whitespace().next().and_then(|n| n.parse().ok()))
            .unwrap_or(0)
    };
    du("/home") + du("/var/lib/flatpak") + du("/var/lib/containers") + du("/root")
}

/// Create the ABRoot partitions. `spec` is a whole disk to dedicate
/// (`/dev/vdb`) or `free:/dev/vda` to use unpartitioned space on a disk.
pub fn partition(spec: &str) -> Result<Layout> {
    let (disk, whole) = match spec.strip_prefix("free:") {
        Some(d) => (d.to_string(), false),
        None => (spec.to_string(), true),
    };
    if !Path::new(&disk).exists() {
        bail!("{disk} does not exist");
    }
    let need_var = (data_size_mib() * 12 / 10).max(VAR_MIN_MIB);
    let need = BOOT_MIB + ROOT_PV_MIB + need_var;
    if whole {
        // Refuse to wipe a disk that holds mounted filesystems.
        let mounted = try_run("lsblk", &["-n", "-o", "MOUNTPOINTS", &disk]).unwrap_or_default();
        if mounted.lines().any(|l| !l.trim().is_empty()) {
            bail!(
                "{disk} has mounted filesystems; give a dedicated disk, or free:{disk} to use its free space"
            );
        }
        let size = try_run("blockdev", &["--getsize64", &disk])
            .and_then(|s| s.trim().parse::<u64>().ok())
            .unwrap_or(0)
            / 1048576;
        if size < need {
            bail!("{disk} is {size} MiB; ABRoot volumes plus your data need about {need} MiB");
        }
        step(format!(
            "partitioning {disk} for ABRoot (vos-boot, vos-root LVM, vos-var)"
        ));
        let script = format!("label: gpt\n{}", sfdisk_parts(None));
        if !util::dry_run() {
            util::run_stdin(
                "sfdisk",
                &["--wipe", "always", "--wipe-partitions", "always", &disk],
                &script,
            )?;
        }
        let _ = try_run("udevadm", &["settle"]);
        return Ok(Layout {
            boot: part_dev(&disk, 1),
            pv: part_dev(&disk, 2),
            var: part_dev(&disk, 3),
            disk,
        });
    }
    let biggest = free_regions(&disk)
        .into_iter()
        .max_by_key(|r| r.1)
        .unwrap_or((0, 0));
    if biggest.1 < need {
        bail!(
            "largest free region on {disk} is {} MiB; ABRoot volumes plus your data need about {need} MiB. \
             Free up space (shrink a partition) or pass a second disk",
            biggest.1
        );
    }
    let before: Vec<String> = list_parts(&disk);
    step(format!(
        "creating ABRoot partitions in free space on {disk}"
    ));
    let script = sfdisk_parts(Some(need_var));
    if !util::dry_run() {
        util::run_stdin("sfdisk", &["--append", "--no-reread", &disk], &script)?;
        let _ = try_run("partx", &["-a", &disk]);
        let _ = try_run("udevadm", &["settle"]);
    }
    let new: Vec<String> = list_parts(&disk)
        .into_iter()
        .filter(|p| !before.contains(p))
        .collect();
    if new.len() != 3 {
        bail!("expected 3 new partitions on {disk}, found {:?}", new);
    }
    Ok(Layout {
        disk,
        boot: new[0].clone(),
        pv: new[1].clone(),
        var: new[2].clone(),
    })
}

fn list_parts(disk: &str) -> Vec<String> {
    try_run("lsblk", &["-ln", "-o", "PATH,TYPE", disk])
        .unwrap_or_default()
        .lines()
        .filter(|l| l.ends_with("part"))
        .filter_map(|l| l.split_whitespace().next().map(str::to_string))
        .collect()
}

fn mkfs_and_lvm(l: &Layout) -> Result<()> {
    step("creating filesystems and the vos-root thin pool");
    let r = |p: &str, a: &[&str]| util::run_visible(p, a);
    r("mkfs.ext4", &["-q", "-F", "-L", "vos-boot", &l.boot])?;
    r("mkfs.btrfs", &["-q", "-f", "-L", "vos-var", &l.var])?;
    r("pvcreate", &["-ff", "-y", &l.pv])?;
    r("vgcreate", &["vos-root", &l.pv])?;
    r("lvcreate", &["-y", "-L", "1G", "-n", "init", "vos-root"])?;
    r(
        "mkfs.ext4",
        &["-q", "-F", "-L", "vos-init", "/dev/vos-root/init"],
    )?;
    r(
        "lvcreate",
        &["-y", "-l", "90%FREE", "-n", "root", "vos-root"],
    )?;
    r(
        "lvcreate",
        &["-y", "-L", "512M", "-n", "root-meta", "vos-root"],
    )?;
    r(
        "lvconvert",
        &[
            "-y",
            "--type",
            "thin-pool",
            "--poolmetadata",
            "vos-root/root-meta",
            "vos-root/root",
        ],
    )?;
    r(
        "lvcreate",
        &["-y", "-V", "19G", "-T", "vos-root/root", "-n", "root-a"],
    )?;
    r(
        "lvcreate",
        &["-y", "-V", "19G", "-T", "vos-root/root", "-n", "root-b"],
    )?;
    r(
        "mkfs.btrfs",
        &["-q", "-f", "-L", "vos-a", "/dev/vos-root/root-a"],
    )?;
    r(
        "mkfs.btrfs",
        &["-q", "-f", "-L", "vos-b", "/dev/vos-root/root-b"],
    )?;
    Ok(())
}

fn uuid(dev: &str) -> Result<String> {
    Ok(run("blkid", &["-s", "UUID", "-o", "value", dev])?
        .trim()
        .to_string())
}

fn mount(src: &str, dst: &Path, opts: &[&str]) -> Result<()> {
    fs::create_dir_all(dst)?;
    let mut a: Vec<String> = opts.iter().map(|s| s.to_string()).collect();
    a.push(src.into());
    a.push(dst.display().to_string());
    util::run_visible("mount", &a)
}

fn chroot(root: &Path, cmd: &str) -> Result<()> {
    util::run_visible(
        "chroot",
        &[root.display().to_string().as_str(), "/bin/sh", "-c", cmd],
    )
}

/// Image digest ABRoot compares against the registry to decide on upgrades.
fn upstream_digest(image: &str) -> String {
    try_run(
        "podman",
        &["image", "inspect", "--format", "{{.Digest}}", image],
    )
    .map(|s| s.trim().to_string())
    .unwrap_or_default()
}

fn derived_built(plan: &Plan) -> bool {
    try_run("podman", &["image", "exists", &plan.derived_image]).is_some()
}

fn disk_and_partnum(part: &str) -> Result<(String, String)> {
    let pk = run("lsblk", &["-n", "-o", "PKNAME", part])?
        .trim()
        .to_string();
    let num = fs::read_to_string(format!(
        "/sys/class/block/{}/partition",
        part.trim_start_matches("/dev/")
    ))?
    .trim()
    .to_string();
    Ok((format!("/dev/{pk}"), num))
}

pub fn apply(m: &Manifest, plan: &Plan, disk: Option<&str>, reboot: bool) -> Result<()> {
    if !util::is_root() {
        bail!("plexy apply must run as root");
    }
    if !m.boot.uefi {
        bail!("ABRoot targets require UEFI boot");
    }
    util::ensure_tools(&[
        ("sfdisk", "fdisk"),
        ("pvcreate", "lvm2"),
        ("mkfs.btrfs", "btrfs-progs"),
        ("mkfs.ext4", "e2fsprogs"),
        ("efibootmgr", "efibootmgr"),
        ("podman", "podman"),
    ])?;
    let Some(spec) = disk else {
        bail!(
            "ABRoot needs its own volumes: pass --abroot-disk /dev/sdX (a dedicated disk, wiped) or \
             --abroot-disk free:/dev/sdX (unpartitioned space). The current system is left untouched"
        );
    };
    let esp = m
        .boot
        .esp
        .clone()
        .context("no EFI system partition mounted at /boot/efi")?;
    let image = if derived_built(plan) {
        plan.derived_image.clone()
    } else {
        plan.target_image.clone()
    };
    crate::target::pull(&image)?;

    let layout = partition(spec)?;
    mkfs_and_lvm(&layout)?;

    let a = PathBuf::from(MNT).join("a");
    step("mounting the new root A");
    mount("/dev/vos-root/root-a", &a, &[])?;
    mount(&layout.var, &a.join("var"), &[])?;

    step(format!("unpacking {image} into root A"));
    let cname = format!("plexy-abroot-{}", util::now_unix());
    run("podman", &["create", "--name", &cname, &image, "/bin/true"])?;
    let sh = format!(
        "podman export {cname} | tar -x --numeric-owner --xattrs --xattrs-include='*' -C {}",
        a.display()
    );
    let st = run("/bin/sh", &["-c", &sh]);
    let _ = run("podman", &["rm", "-f", &cname]);
    st?;
    mount(&layout.boot, &a.join("boot"), &[])?;
    mount("/boot/efi", &a.join("boot/efi"), &["--bind"])?;

    step("arranging the ABRoot filesystem structure");
    fs::create_dir_all(a.join("part-future"))?;
    let media = a.join("media");
    let _ = fs::remove_dir_all(&media);
    let _ = fs::remove_file(&media);
    std::os::unix::fs::symlink("run/media", &media)?;
    for d in ["home", "mnt", "root", "srv", "opt"] {
        let p = a.join(d);
        if fs::symlink_metadata(&p)
            .map(|m| !m.file_type().is_symlink())
            .unwrap_or(true)
        {
            let _ = fs::remove_dir_all(&p);
            fs::create_dir_all(a.join("var").join(d))?;
            std::os::unix::fs::symlink(format!("var/{d}"), &p)?;
        }
    }
    let digest = upstream_digest(&plan.target_image);
    write_file(
        &a.join("abimage.abr"),
        format!(
            "{{\n    \"digest\":\"{digest}\",\n    \"timestamp\":\"{}\",\n    \"image\":\"{}\"\n}}\n",
            util::now_unix(),
            plan.target_image
        ),
    )?;

    // /etc is an overlay: lower = image, upper = var/lib/abroot/etc/vos-a.
    // Everything written to /etc from here on lands in the upper dir, which is
    // what ABRoot's three-way merge treats as the user's changes.
    for d in ["vos-a", "vos-b", "vos-a-work", "vos-b-work"] {
        fs::create_dir_all(a.join("var/lib/abroot/etc").join(d))?;
    }
    let ov = format!(
        "lowerdir={0}/etc,upperdir={0}/var/lib/abroot/etc/vos-a,workdir={0}/var/lib/abroot/etc/vos-a-work",
        a.display()
    );
    mount("overlay", &a.join("etc"), &["-t", "overlay", "-o", &ov])?;

    // ABRoot settings: thin provisioning on; layered packages recorded so
    // `abroot upgrade` keeps installing them.
    let base_cfg = read_opt(a.join("usr/share/abroot/abroot.json")).unwrap_or_else(|| "{}".into());
    let mut cfg: serde_json::Value =
        serde_json::from_str(&base_cfg).unwrap_or(serde_json::json!({}));
    cfg["thinProvisioning"] = serde_json::json!(true);
    cfg["thinInitVolume"] = serde_json::json!("vos-init");
    let cfg_s = serde_json::to_string_pretty(&cfg)?;
    write_file(&a.join("etc/abroot/abroot.json"), &cfg_s)?;
    write_file(&a.join("usr/share/abroot/abroot.json"), &cfg_s)?;
    let layered = plan.names_for(Dest::Image);
    if !layered.is_empty() {
        write_file(
            &a.join("etc/abroot/packages.add"),
            layered.join("\n") + "\n",
        )?;
    }

    // fstab: ABRoot rewrites the / line on boot; /boot and the ESP are ours.
    let mut fstab = format!(
        "UUID={} / btrfs defaults 0 0\nUUID={} /boot ext4 defaults 0 2\nUUID={} /boot/efi vfat umask=0077 0 2\n",
        uuid("/dev/vos-root/root-a")?,
        uuid(&layout.boot)?,
        uuid(&esp)?
    );
    for l in translate_fstab(&read_opt("/etc/fstab").unwrap_or_default()) {
        let tgt = l.split_whitespace().nth(1).unwrap_or("");
        // old /home and /var are copied into vos-var; don't mount them over it.
        if tgt == "/var" || tgt.starts_with("/var/home") || tgt == "/var/roothome" {
            continue;
        }
        fstab.push_str(&l);
        fstab.push('\n');
    }
    write_file(&a.join("etc/fstab"), fstab)?;

    step("carrying accounts and configuration");
    let r = |p: &str| read_opt(root_join(&a, p)).unwrap_or_default();
    let merged = merge_accounts(
        m,
        plan.target_family,
        &r("/etc/passwd"),
        &r("/etc/shadow"),
        &r("/etc/group"),
        &r("/etc/gshadow"),
        "",
        "",
        &read_opt("/etc/shadow").unwrap_or_default(),
        &read_opt("/etc/gshadow").unwrap_or_default(),
    );
    for (p, c, mode) in [
        ("/etc/passwd", &merged.passwd, 0o644),
        ("/etc/shadow", &merged.shadow, 0o640),
        ("/etc/group", &merged.group, 0o644),
        ("/etc/gshadow", &merged.gshadow, 0o640),
    ] {
        let path = root_join(&a, p);
        write_file(&path, c)?;
        fs::set_permissions(&path, fs::Permissions::from_mode(mode))?;
    }
    if let Some(g) = parse_group(&r("/etc/group"))
        .into_iter()
        .find(|g| g.name == "shadow")
    {
        for p in ["/etc/shadow", "/etc/gshadow"] {
            let _ = std::os::unix::fs::chown(root_join(&a, p), Some(0), Some(g.gid));
        }
    }
    let mut n = 0;
    for c in plan
        .configs
        .iter()
        .filter(|c| matches!(c.action, ConfigAction::Etc | ConfigAction::Brew))
    {
        let dst = root_join(
            &a,
            etc_translate(&c.path, plan.source_family, plan.target_family),
        );
        if fs::symlink_metadata(&c.path).is_ok()
            && apply::copy_preserving(Path::new(&c.path), &dst).is_ok()
        {
            n += 1;
        }
    }
    for p in ["/etc/hostname", "/etc/machine-id"] {
        if Path::new(p).exists() {
            apply::copy_preserving(Path::new(p), &root_join(&a, p))?;
        }
    }
    if let Ok(tz) = fs::read_link("/etc/localtime") {
        let d = a.join("etc/localtime");
        let _ = fs::remove_file(&d);
        std::os::unix::fs::symlink(tz, d)?;
    }
    info(format!("  {n} config files carried"));
    let dstr = a.display().to_string();
    let mut en = 0;
    for u in &plan.units_to_enable {
        if try_run("systemctl", &["--root", &dstr, "enable", u]).is_some() {
            en += 1;
        }
    }
    info(format!("  {en} services enabled as on the old system"));

    step("installing the boot chain (initramfs, GRUB, EFI entry)");
    for (src, dst) in [
        ("/dev", "dev"),
        ("/proc", "proc"),
        ("/sys", "sys"),
        ("/run", "run"),
    ] {
        mount(src, &a.join(dst), &["--rbind"])?;
    }
    mount("/dev/vos-root/init", &a.join("boot/init"), &[])?;
    fs::create_dir_all(a.join("boot/init/vos-a"))?;
    fs::create_dir_all(a.join("boot/init/vos-b"))?;
    let kver = fs::read_dir(a.join("usr/lib/modules"))?
        .flatten()
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .max()
        .context("no kernel in the image")?;
    chroot(
        &a,
        "lpkg --unlock >/dev/null 2>&1; if ls /boot/initrd.img-* >/dev/null 2>&1; then update-initramfs -u -k all; else update-initramfs -c -k all; fi; lpkg --lock >/dev/null 2>&1; true",
    )?;
    for e in fs::read_dir(a.join("boot"))?.flatten() {
        let name = e.file_name().to_string_lossy().into_owned();
        if ["vmlinuz", "initrd.img", "config-", "System.map"]
            .iter()
            .any(|p| name.starts_with(p))
            && e.path().is_file()
        {
            fs::rename(e.path(), a.join("boot/init/vos-a").join(&name))?;
        }
    }
    let vmlinuz = a.join(format!("boot/init/vos-a/vmlinuz-{kver}"));
    let from_mod = a.join(format!("usr/lib/modules/{kver}/vmlinuz"));
    if !vmlinuz.exists() && from_mod.exists() {
        fs::copy(&from_mod, &vmlinuz)?;
    }
    if !a
        .join(format!("boot/init/vos-a/initrd.img-{kver}"))
        .exists()
    {
        bail!("initramfs for {kver} was not generated");
    }
    let mut kargs = read_opt(a.join("etc/abroot/kargs"))
        .unwrap_or_else(|| "quiet splash bgrt_disable $vt_handoff lsm=integrity".into())
        .trim()
        .to_string();
    for k in &plan.kargs {
        kargs.push(' ');
        kargs.push_str(k);
    }
    write_file(
        &a.join("boot/init/vos-a/abroot.cfg"),
        abroot_cfg(&kver, "/dev/mapper/vos--root-root--a", &kargs),
    )?;
    chroot(
        &a,
        "grub-install --no-nvram --bootloader-id=vanilla --boot-directory=/boot --target=x86_64-efi \
         --efi-directory=/boot/efi --uefi-secure-boot",
    )?;
    write_file(&a.join("boot/grub/grub.cfg"), BOOT_GRUB_CFG)?;
    let (esp_disk, esp_part) = disk_and_partnum(&esp)?;
    let loader = if a.join("boot/efi/EFI/vanilla/shimx64.efi").exists() {
        "\\EFI\\vanilla\\shimx64.efi"
    } else {
        "\\EFI\\vanilla\\grubx64.efi"
    };
    util::run_visible(
        "efibootmgr",
        &[
            "--create",
            "--disk",
            &esp_disk,
            "--part",
            &esp_part,
            "--label",
            "Vanilla OS",
            "--loader",
            loader,
        ],
    )?;

    step("copying your data into vos-var (home, flatpaks, service state)");
    copy_data(&a)?;
    let new_users = parse_passwd(&r("/etc/passwd"));
    let new_groups = parse_group(&r("/etc/group"));
    let uids = apply::id_remap(&m.accounts.all_users, &new_users);
    let gids = apply::gid_remap(&m.accounts.all_groups, &new_groups);
    if !uids.is_empty() || !gids.is_empty() {
        let n = apply::chown_tree(
            &a.join("var"),
            &uids,
            &gids,
            &["lib/containers", "home", "lib/flatpak"],
        );
        info(format!(
            "  {n} files re-owned for system accounts whose ids differ"
        ));
    }

    // Plexy itself, for the first-boot/first-login stages.
    apply::install_self(&a.join("var/usrlocal/bin/plexy"))?;
    write_file(
        &a.join("etc/systemd/system/plexy-firstboot.service"),
        FIRSTBOOT_UNIT,
    )?;
    write_file(
        &a.join("etc/systemd/user/plexy-firstlogin.service"),
        FIRSTLOGIN_UNIT,
    )?;
    let _ = try_run(
        "systemctl",
        &["--root", &dstr, "enable", "plexy-firstboot.service"],
    );
    let _ = try_run(
        "systemctl",
        &[
            "--root",
            &dstr,
            "--global",
            "enable",
            "plexy-firstlogin.service",
        ],
    );
    write_file(
        &a.join("var/lib/plexy/plan.json"),
        serde_json::to_string_pretty(plan)?,
    )?;
    let tb = Path::new("/var/lib/plexy/staging/toolbox.tar");
    if tb.exists() {
        fs::create_dir_all(a.join("var/lib/plexy/staging"))?;
        run(
            "cp",
            &[
                tb.display().to_string().as_str(),
                &a.join("var/lib/plexy/staging/").display().to_string(),
            ],
        )?;
    }

    step("unmounting");
    let _ = run("sync", &[] as &[&str]);
    let _ = run("umount", &["-R", &a.display().to_string()]);
    let _ = run("vgchange", &["-an", "vos-root"]);
    println!("\n  Vanilla OS is installed on ABRoot volumes and is now the first boot entry.");
    println!(
        "  Your previous system is untouched and stays available in the firmware boot menu.\n"
    );
    if reboot {
        run("systemctl", &["reboot"])?;
    }
    Ok(())
}

fn copy_data(a: &Path) -> Result<()> {
    let var = a.join("var");
    let cp = |src: &Path, dst_dir: &Path| -> Result<()> {
        fs::create_dir_all(dst_dir)?;
        util::run_visible(
            "cp",
            &[
                "-a",
                "--reflink=auto",
                &src.display().to_string(),
                &dst_dir.display().to_string(),
            ],
        )
    };
    for (old, new) in [("/home", "home"), ("/root", "root")] {
        if let Ok(rd) = fs::read_dir(old) {
            for e in rd.flatten() {
                cp(&e.path(), &var.join(new))?;
            }
        }
    }
    for top in fs::read_dir("/var")?.flatten() {
        let name = top.file_name().to_string_lossy().into_owned();
        if !top.path().is_dir() || ["home", "tmp", "run", "lock"].contains(&name.as_str()) {
            continue;
        }
        for sub in fs::read_dir(top.path())?.flatten() {
            let rel = format!("{name}/{}", sub.file_name().to_string_lossy());
            if apply::var_entry_left_behind(&rel) || rel.starts_with("lib/plexy") {
                continue;
            }
            // The image's own state (dpkg db, apt lists, ...) wins.
            if var.join(&rel).exists() {
                continue;
            }
            cp(&sub.path(), &var.join(&name))?;
        }
    }
    if Path::new("/usr/local").is_dir() {
        fs::create_dir_all(var.join("usrlocal"))?;
        let _ = run(
            "cp",
            &[
                "-a",
                "--reflink=auto",
                "/usr/local/.",
                &var.join("usrlocal").display().to_string(),
            ],
        );
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sfdisk_script() {
        let s = sfdisk_parts(None);
        assert!(s.starts_with("size=1024MiB, type=linux, name=vos-boot\n"));
        assert!(s.contains("type=lvm, name=vos-root"));
        assert!(s.ends_with("type=linux, name=vos-var\n"));
        assert!(sfdisk_parts(Some(30000)).contains("size=30000MiB, type=linux, name=vos-var"));
    }

    #[test]
    fn partition_device_names() {
        assert_eq!(part_dev("/dev/vdb", 2), "/dev/vdb2");
        assert_eq!(part_dev("/dev/nvme0n1", 3), "/dev/nvme0n1p3");
        assert_eq!(part_dev("/dev/mmcblk0", 1), "/dev/mmcblk0p1");
    }

    #[test]
    fn abroot_cfg_format() {
        let c = abroot_cfg(
            "7.1.3+deb14-amd64",
            "/dev/mapper/vos--root-root--a",
            "quiet splash",
        );
        assert!(c.contains(
            "linux   (lvm/vos--root-init)/vos-a/vmlinuz-7.1.3+deb14-amd64 root=/dev/mapper/vos--root-root--a quiet splash"
        ));
        assert!(c.contains("initrd  (lvm/vos--root-init)/vos-a/initrd.img-7.1.3+deb14-amd64"));
    }

    #[test]
    fn boot_menu_has_both_states() {
        assert!(
            BOOT_GRUB_CFG.contains("--class abroot-a")
                && BOOT_GRUB_CFG.contains("--class abroot-b")
        );
        assert!(BOOT_GRUB_CFG.contains("Current State (A)"));
    }
}
