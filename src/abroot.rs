//! ABRoot backend (Vanilla OS): A/B root volumes + shared var.
//!
//! ABRoot v2 (Vanilla OS 3) has no "install next to the running system" mode
//! like bootc's to-existing-root, and its layout needs dedicated volumes:
//!
//! ```text
//!   vos-boot  ext4 partition           /boot   (grub.cfg with the A/B menu)
//!   vos-root  LVM VG
//!     ├─ init        ext4 "vos-init"   kernels + abroot.cfg per root
//!     └─ root (thin pool)
//!          ├─ root-a btrfs "vos-a"     the running root
//!          └─ root-b btrfs "vos-b"     the next/previous root
//!   vos-var   btrfs partition          /var    (home, flatpaks, /etc overlay upper)
//! ```
//!
//! Plexy builds exactly this (mirroring vanilla-installer/Albius) on a disk or
//! free space the user designates, unpacks the image (plus layered packages)
//! into root A, copies home and /var data into vos-var, and carries accounts
//! and configuration into the /etc overlay's upper directory so ABRoot's
//! three-way /etc merge preserves them across upgrades. The old system is not
//! modified, so it remains bootable from the firmware menu as a fallback.

use crate::apply::{self, FIRSTBOOT_UNIT, FIRSTLOGIN_UNIT, merge_accounts, translate_fstab};
use crate::manifest::Manifest;
use crate::plan::{ConfigAction, Dest, Plan, etc_translate};
use crate::state::{parse_group, parse_passwd};
use crate::util::{self, info, read_opt, root_join, run, step, try_run, write_file};
use anyhow::{Context, Result, bail};
use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};

const MNT: &str = "/mnt/plexy-abroot";
const BOOT_MIB: u64 = 1024;
const ROOT_PV_MIB: u64 = 22 * 1024;
const VAR_MIN_MIB: u64 = 20 * 1024;

